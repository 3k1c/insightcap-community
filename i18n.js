document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('lang') || 'en';
    setLanguage(savedLang);

    // Custom Dropdown Logic
    const langBtn = document.getElementById('lang-dropdown-btn');
    const langMenu = document.getElementById('lang-dropdown-menu');

    if (langBtn && langMenu) {
        // Toggle menu
        langBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            const isOpen = !langMenu.classList.contains('opacity-0');
            if (isOpen) {
                closeLangMenu();
            } else {
                openLangMenu();
            }
        });

        // Close when clicking outside
        document.addEventListener('click', (e) => {
            if (!langBtn.contains(e.target) && !langMenu.contains(e.target)) {
                closeLangMenu();
            }
        });

        // Handle language selection
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
                const lang = e.currentTarget.dataset.lang;
                setLanguage(lang);
                closeLangMenu();
            });
        });
    }

    function openLangMenu() {
        langMenu.classList.remove('opacity-0', 'invisible', 'scale-95');
        langMenu.classList.add('opacity-100', 'visible', 'scale-100');
    }

    function closeLangMenu() {
        langMenu.classList.remove('opacity-100', 'visible', 'scale-100');
        langMenu.classList.add('opacity-0', 'invisible', 'scale-95');
    }
});

function setLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('lang', lang);

    // Update custom dropdown label and checkmarks
    const labels = {
        'en': 'EN',
        'zh_tw': '繁中',
        'zh_cn': '简中'
    };
    const labelEl = document.getElementById('current-lang-label');
    if (labelEl) labelEl.textContent = labels[lang];

    document.querySelectorAll('.lang-btn').forEach(btn => {
        const checkIcon = btn.querySelector('.check-icon');
        if (btn.dataset.lang === lang) {
            btn.classList.add('text-white', 'bg-white/10');
            btn.classList.remove('text-slate-300');
            if (checkIcon) checkIcon.classList.remove('opacity-0');
        } else {
            btn.classList.remove('text-white', 'bg-white/10');
            btn.classList.add('text-slate-300');
            if (checkIcon) checkIcon.classList.add('opacity-0');
        }
    });

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (translations[lang][key]) {
            if (el.dataset.i18nHtml === "true") {
                el.innerHTML = translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });
}
